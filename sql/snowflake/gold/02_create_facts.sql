
-- =====================================================
-- CommerceFlow: Snowflake Gold Fact Tables
-- =====================================================

USE DATABASE COMMERCEFLOW_DB;
USE SCHEMA GOLD;


-- 1. Orders Fact Table
CREATE TABLE IF NOT EXISTS FACT_ORDERS (
    ORDER_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    ORDER_ID VARCHAR(50) NOT NULL UNIQUE,
    CUSTOMER_KEY NUMBER(38,0) NOT NULL
        REFERENCES DIM_CUSTOMERS(CUSTOMER_KEY),
    PURCHASE_DATE_KEY NUMBER(10,0)
        REFERENCES DIM_DATE(DATE_KEY),
    ORDER_STATUS VARCHAR(30),
    ORDER_PURCHASE_TIMESTAMP TIMESTAMP_NTZ,
    ORDER_APPROVED_AT TIMESTAMP_NTZ,
    ORDER_DELIVERED_CARRIER_DATE TIMESTAMP_NTZ,
    ORDER_DELIVERED_CUSTOMER_DATE TIMESTAMP_NTZ,
    ORDER_ESTIMATED_DELIVERY_DATE TIMESTAMP_NTZ
);


-- 2. Order Items Fact Table
CREATE TABLE IF NOT EXISTS FACT_ORDER_ITEMS (
    ORDER_ITEM_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    ORDER_ID VARCHAR(50) NOT NULL,
    ORDER_ITEM_ID NUMBER(10,0) NOT NULL,
    CUSTOMER_KEY NUMBER(38,0) NOT NULL
        REFERENCES DIM_CUSTOMERS(CUSTOMER_KEY),
    PRODUCT_KEY NUMBER(38,0) NOT NULL
        REFERENCES DIM_PRODUCTS(PRODUCT_KEY),
    SELLER_KEY NUMBER(38,0) NOT NULL
        REFERENCES DIM_SELLERS(SELLER_KEY),
    SHIPPING_LIMIT_DATE TIMESTAMP_NTZ,
    PRICE NUMBER(12,2),
    FREIGHT_VALUE NUMBER(12,2),
    UNIQUE (ORDER_ID, ORDER_ITEM_ID)
);


-- 3. Payments Fact Table
CREATE TABLE IF NOT EXISTS FACT_PAYMENTS (
    PAYMENT_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    ORDER_ID VARCHAR(50) NOT NULL,
    CUSTOMER_KEY NUMBER(38,0) NOT NULL
        REFERENCES DIM_CUSTOMERS(CUSTOMER_KEY),
    PAYMENT_SEQUENTIAL NUMBER(10,0) NOT NULL,
    PAYMENT_TYPE VARCHAR(30),
    PAYMENT_INSTALLMENTS NUMBER(10,0),
    PAYMENT_VALUE NUMBER(12,2),
    UNIQUE (ORDER_ID, PAYMENT_SEQUENTIAL)
);
