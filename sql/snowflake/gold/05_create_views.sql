USE DATABASE COMMERCEFLOW_DB;
USE SCHEMA GOLD;


-- 1. Monthly Sales Analysis
CREATE OR REPLACE VIEW V_MONTHLY_SALES AS
SELECT
    d.YEAR_NUMBER,
    d.MONTH_NUMBER,
    d.MONTH_NAME,
    COUNT(DISTINCT o.ORDER_ID) AS TOTAL_ORDERS,
    SUM(oi.PRICE) AS PRODUCT_SALES,
    SUM(oi.FREIGHT_VALUE) AS FREIGHT_REVENUE,
    SUM(oi.PRICE + oi.FREIGHT_VALUE) AS TOTAL_SALES,
    ROUND(
        SUM(oi.PRICE) / NULLIF(COUNT(DISTINCT o.ORDER_ID), 0),
        2
    ) AS AVERAGE_ORDER_VALUE
FROM FACT_ORDER_ITEMS oi
JOIN FACT_ORDERS o
    ON oi.ORDER_ID = o.ORDER_ID
JOIN DIM_DATE d
    ON o.PURCHASE_DATE_KEY = d.DATE_KEY
GROUP BY
    d.YEAR_NUMBER,
    d.MONTH_NUMBER,
    d.MONTH_NAME;


-- 2. Customer Sales Analysis
CREATE OR REPLACE VIEW V_CUSTOMER_SALES AS
SELECT
    dc.CUSTOMER_UNIQUE_ID,
    dc.CUSTOMER_CITY,
    dc.CUSTOMER_STATE,
    COUNT(DISTINCT fo.ORDER_ID) AS TOTAL_ORDERS,
    SUM(foi.PRICE) AS TOTAL_PRODUCT_SPEND,
    SUM(foi.FREIGHT_VALUE) AS TOTAL_FREIGHT,
    ROUND(
        SUM(foi.PRICE) / NULLIF(COUNT(DISTINCT fo.ORDER_ID), 0),
        2
    ) AS AVERAGE_ORDER_VALUE
FROM DIM_CUSTOMERS dc
JOIN FACT_ORDERS fo
    ON dc.CUSTOMER_KEY = fo.CUSTOMER_KEY
JOIN FACT_ORDER_ITEMS foi
    ON fo.ORDER_ID = foi.ORDER_ID
GROUP BY
    dc.CUSTOMER_UNIQUE_ID,
    dc.CUSTOMER_CITY,
    dc.CUSTOMER_STATE;


-- 3. Product Performance Analysis
CREATE OR REPLACE VIEW V_PRODUCT_PERFORMANCE AS
SELECT
    dp.PRODUCT_ID,
    dp.PRODUCT_CATEGORY_NAME_ENGLISH AS PRODUCT_CATEGORY,
    COUNT(DISTINCT foi.ORDER_ID) AS TOTAL_ORDERS,
    COUNT(*) AS UNITS_SOLD,
    SUM(foi.PRICE) AS PRODUCT_SALES,
    SUM(foi.FREIGHT_VALUE) AS FREIGHT_REVENUE,
    ROUND(AVG(foi.PRICE), 2) AS AVERAGE_PRODUCT_PRICE
FROM FACT_ORDER_ITEMS foi
JOIN DIM_PRODUCTS dp
    ON foi.PRODUCT_KEY = dp.PRODUCT_KEY
GROUP BY
    dp.PRODUCT_ID,
    dp.PRODUCT_CATEGORY_NAME_ENGLISH;


-- 4. Seller Performance Analysis
CREATE OR REPLACE VIEW V_SELLER_PERFORMANCE AS
SELECT
    ds.SELLER_ID,
    ds.SELLER_CITY,
    ds.SELLER_STATE,
    COUNT(DISTINCT foi.ORDER_ID) AS TOTAL_ORDERS,
    COUNT(*) AS UNITS_SOLD,
    SUM(foi.PRICE) AS PRODUCT_SALES,
    SUM(foi.FREIGHT_VALUE) AS FREIGHT_REVENUE,
    ROUND(AVG(foi.PRICE), 2) AS AVERAGE_ITEM_PRICE
FROM FACT_ORDER_ITEMS foi
JOIN DIM_SELLERS ds
    ON foi.SELLER_KEY = ds.SELLER_KEY
GROUP BY
    ds.SELLER_ID,
    ds.SELLER_CITY,
    ds.SELLER_STATE;


-- 5. Payment Analysis
CREATE OR REPLACE VIEW V_PAYMENT_ANALYSIS AS
SELECT
    PAYMENT_TYPE,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(PAYMENT_VALUE) AS TOTAL_PAYMENT_VALUE,
    ROUND(AVG(PAYMENT_VALUE), 2) AS AVERAGE_PAYMENT_VALUE,
    SUM(PAYMENT_INSTALLMENTS) AS TOTAL_INSTALLMENTS
FROM FACT_PAYMENTS
GROUP BY PAYMENT_TYPE;


-- 6. Delivery Performance Analysis
CREATE OR REPLACE VIEW V_DELIVERY_PERFORMANCE AS
SELECT
    ORDER_STATUS,
    COUNT(*) AS TOTAL_ORDERS,
    COUNT(ORDER_DELIVERED_CUSTOMER_DATE) AS DELIVERED_ORDERS,
    COALESCE(
        COUNT_IF(
            ORDER_DELIVERED_CUSTOMER_DATE > ORDER_ESTIMATED_DELIVERY_DATE
        ), 0
    ) AS LATE_DELIVERIES,
    COALESCE(
        COUNT_IF(
            ORDER_DELIVERED_CUSTOMER_DATE <= ORDER_ESTIMATED_DELIVERY_DATE
        ), 0
    ) AS ON_TIME_DELIVERIES,
    ROUND(
        AVG(
            DATEDIFF(
                SECOND,
                ORDER_PURCHASE_TIMESTAMP,
                ORDER_DELIVERED_CUSTOMER_DATE
            ) / 86400.0
        ),
        2
    ) AS AVG_DELIVERY_DAYS
FROM FACT_ORDERS
GROUP BY ORDER_STATUS;


-- 7. Review Analysis
CREATE OR REPLACE VIEW V_REVIEW_ANALYSIS AS
SELECT
    r."review_score" AS REVIEW_SCORE,
    COUNT(*) AS TOTAL_REVIEWS,
    COUNT(DISTINCT r."order_id") AS REVIEWED_ORDERS,
    COUNT(r."review_comment_message") AS REVIEWS_WITH_COMMENTS,
    ROUND(
        AVG(LENGTH(r."review_comment_message")),
        2
    ) AS AVG_COMMENT_LENGTH
FROM SILVER.OLIST_ORDER_REVIEWS r
JOIN FACT_ORDERS o
    ON r."order_id" = o.ORDER_ID
GROUP BY r."review_score";
