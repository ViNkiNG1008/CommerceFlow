USE DATABASE COMMERCEFLOW_DB;
USE SCHEMA GOLD;


-- 1. Dimension Row Counts
SELECT 'DIM_CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM DIM_CUSTOMERS
UNION ALL
SELECT 'DIM_PRODUCTS', COUNT(*) FROM DIM_PRODUCTS
UNION ALL
SELECT 'DIM_SELLERS', COUNT(*) FROM DIM_SELLERS
UNION ALL
SELECT 'DIM_DATE', COUNT(*) FROM DIM_DATE;


-- 2. Fact Row Counts
SELECT 'FACT_ORDERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM FACT_ORDERS
UNION ALL
SELECT 'FACT_ORDER_ITEMS', COUNT(*) FROM FACT_ORDER_ITEMS
UNION ALL
SELECT 'FACT_PAYMENTS', COUNT(*) FROM FACT_PAYMENTS;


-- 3. Primary Business Key Uniqueness
SELECT
    COUNT(*) - COUNT(DISTINCT CUSTOMER_ID) AS DUPLICATE_CUSTOMERS
FROM DIM_CUSTOMERS;

SELECT
    COUNT(*) - COUNT(DISTINCT PRODUCT_ID) AS DUPLICATE_PRODUCTS
FROM DIM_PRODUCTS;

SELECT
    COUNT(*) - COUNT(DISTINCT SELLER_ID) AS DUPLICATE_SELLERS
FROM DIM_SELLERS;

SELECT
    COUNT(*) - COUNT(DISTINCT ORDER_ID) AS DUPLICATE_ORDERS
FROM FACT_ORDERS;


-- 4. Composite Key Validation
SELECT
    COUNT(*) - COUNT(DISTINCT ORDER_ID || '-' || ORDER_ITEM_ID)
        AS DUPLICATE_ORDER_ITEMS
FROM FACT_ORDER_ITEMS;

SELECT
    COUNT(*) - COUNT(DISTINCT ORDER_ID || '-' || PAYMENT_SEQUENTIAL)
        AS DUPLICATE_PAYMENTS
FROM FACT_PAYMENTS;


-- 5. Foreign Key Validation
SELECT COUNT(*) AS INVALID_ORDER_CUSTOMERS
FROM FACT_ORDERS f
LEFT JOIN DIM_CUSTOMERS d
    ON f.CUSTOMER_KEY = d.CUSTOMER_KEY
WHERE d.CUSTOMER_KEY IS NULL;

SELECT COUNT(*) AS INVALID_ORDER_ITEM_REFERENCES
FROM FACT_ORDER_ITEMS f
LEFT JOIN DIM_CUSTOMERS c
    ON f.CUSTOMER_KEY = c.CUSTOMER_KEY
LEFT JOIN DIM_PRODUCTS p
    ON f.PRODUCT_KEY = p.PRODUCT_KEY
LEFT JOIN DIM_SELLERS s
    ON f.SELLER_KEY = s.SELLER_KEY
WHERE c.CUSTOMER_KEY IS NULL
   OR p.PRODUCT_KEY IS NULL
   OR s.SELLER_KEY IS NULL;

SELECT COUNT(*) AS INVALID_PAYMENT_CUSTOMERS
FROM FACT_PAYMENTS f
LEFT JOIN DIM_CUSTOMERS d
    ON f.CUSTOMER_KEY = d.CUSTOMER_KEY
WHERE d.CUSTOMER_KEY IS NULL;


