-- =====================================================
-- CommerceFlow: Snowflake Gold Dimension Tables
-- =====================================================

CREATE SCHEMA IF NOT EXISTS COMMERCEFLOW_DB.GOLD;

USE DATABASE COMMERCEFLOW_DB;
USE SCHEMA GOLD;

-- 1. Customer Dimension
CREATE TABLE IF NOT EXISTS DIM_CUSTOMERS (
    CUSTOMER_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    CUSTOMER_ID VARCHAR(50) NOT NULL UNIQUE,
    CUSTOMER_UNIQUE_ID VARCHAR(50),
    CUSTOMER_ZIP_CODE_PREFIX NUMBER(10,0),
    CUSTOMER_CITY VARCHAR(100),
    CUSTOMER_STATE CHAR(2)
);

-- 2. Product Dimension
CREATE TABLE IF NOT EXISTS DIM_PRODUCTS (
    PRODUCT_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    PRODUCT_ID VARCHAR(50) NOT NULL UNIQUE,
    PRODUCT_CATEGORY_NAME VARCHAR(100),
    PRODUCT_CATEGORY_NAME_ENGLISH VARCHAR(100),
    PRODUCT_NAME_LENGTH NUMBER(10,0),
    PRODUCT_DESCRIPTION_LENGTH NUMBER(10,0),
    PRODUCT_PHOTOS_QTY NUMBER(10,0),
    PRODUCT_WEIGHT_G NUMBER(10,0),
    PRODUCT_LENGTH_CM NUMBER(10,0),
    PRODUCT_HEIGHT_CM NUMBER(10,0),
    PRODUCT_WIDTH_CM NUMBER(10,0)
);

-- 3. Seller Dimension
CREATE TABLE IF NOT EXISTS DIM_SELLERS (
    SELLER_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    SELLER_ID VARCHAR(50) NOT NULL UNIQUE,
    SELLER_ZIP_CODE_PREFIX NUMBER(10,0),
    SELLER_CITY VARCHAR(100),
    SELLER_STATE CHAR(2)
);

-- 4. Date Dimension
CREATE TABLE IF NOT EXISTS DIM_DATE (
    DATE_KEY NUMBER(10,0) PRIMARY KEY,
    FULL_DATE DATE NOT NULL UNIQUE,
    DAY_OF_MONTH NUMBER(10,0),
    DAY_NAME VARCHAR(10),
    DAY_OF_WEEK NUMBER(10,0),
    WEEK_OF_YEAR NUMBER(10,0),
    MONTH_NUMBER NUMBER(10,0),
    MONTH_NAME VARCHAR(10),
    QUARTER_NUMBER NUMBER(10,0),
    YEAR_NUMBER NUMBER(10,0),
    IS_WEEKEND BOOLEAN
);
